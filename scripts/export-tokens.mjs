// Writes Ditt0's colours for code outside Claude Code: components/foundations/tokens/tokens.json for any
// language, and go/ditt0/tokens_gen.go for Go. tokens.js stays the one place to change a colour.
// Also writes the fixed values the Go package draws with (glyphs, rows, unit steps, big digits) from the modules
// that own them in JS (*.constants.js, units.js) into go/ditt0/constants_gen.go, so Go never repeats them by hand.
// node scripts/export-tokens.mjs           writes the files
// node scripts/export-tokens.mjs --check   exits 1 if any is out of date
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))

// tokens.js is a Claude Code module with no package.json beside it, so plain Node won't load it as ESM; its one
// import only picks the current theme, which the exported tables don't depend on
const source = readFileSync(`${root}components/foundations/tokens/tokens.js`, 'utf8').replace(
    /^import \{ theme \} from .*$/m,
    "const theme = () => 'dark'",
)
const { TOKENS } = await import(`data:text/javascript,${encodeURIComponent(source)}`)
// A module with no imports, loaded the same way: plain Node reads no ES module under components/
const load = (path) => import(`data:text/javascript,${encodeURIComponent(readFileSync(`${root}${path}`, 'utf8'))}`)
const TIMESERIES = 'components/molecules/charts/timeseries/timeseries.constants.js'
const STAT = 'components/molecules/charts/stat/stat.constants.js'
const LEGEND = 'components/atoms/legend/legend.constants.js'
const UNITS = 'components/foundations/units/units.js'
const [ts, stat, legend, units] = await Promise.all([TIMESERIES, STAT, LEGEND, UNITS].map(load))
const JSON_PATH = `${root}components/foundations/tokens/tokens.json`
const GO_PATH = `${root}go/ditt0/tokens_gen.go`
const CONSTANTS_PATH = `${root}go/ditt0/constants_gen.go`

const json = `${JSON.stringify(TOKENS, null, 2)}\n`

const STATUS_FIELDS = { error: 'Error', warning: 'Warning', info: 'Info', healthy: 'Healthy', debug: 'Debug', unknown: 'Unknown', cta: 'CTA' }
const BADGE_FIELDS = { success: 'Success', critical: 'Critical', attention: 'Attention', severe: 'Severe', primary: 'Primary' }
const q = (s) => JSON.stringify(s)

const goTheme = (name, varName) => {
    const status = Object.entries(STATUS_FIELDS)
        .map(([key, field]) => {
            const s = TOKENS.status[name][key]
            return `\t${field}: Status{Bg: ${q(s.bg)}, Text: ${q(s.text)}, Inline: ${q(s.inline)}},`
        })
        .join('\n')
    const badge = Object.entries(BADGE_FIELDS)
        .map(([key, field]) => `${field}: ${q(TOKENS.badge[name][key])}`)
        .join(', ')
    return `var ${varName} = Theme{
\tName: ${q(name)},
${status}
\tBadge:        Badge{${badge}},
\tButtonStroke: ${q(TOKENS.button[name].stroke)},
\tRaised:       Raised{Bg: ${q(TOKENS.raised[name].bg)}, Stroke: ${q(TOKENS.raised[name].stroke)}},
\tSelected:     ${q(TOKENS.selected[name])},
\tSeries:       []string{${TOKENS.series[name].map(q).join(', ')}},
\tSeriesUnset:  ${q(TOKENS.seriesUnset[name])},
}`
}

const goMap = (name, map) =>
    `var ${name} = map[string]string{\n${Object.entries(map).map(([k, v]) => `\t${q(k)}: ${q(v)},`).join('\n')}\n}`

const goSource = `// Code generated by scripts/export-tokens.mjs from components/foundations/tokens/tokens.js. DO NOT EDIT.

package ditt0

${goTheme('dark', 'Dark')}

${goTheme('light', 'Light')}

${goMap('severityStatus', TOKENS.severity)}

${goMap('spanStatusStatus', TOKENS.spanStatus)}
`
// Formatted as gofmt writes it, so the file reads the same whether the script or an editor last touched it
const go = execFileSync('gofmt', { input: goSource, encoding: 'utf8' })

const goSteps = (name, steps) => `var ${name} = []unitStep{${steps.map(([d, s]) => `{${d}, ${q(s)}}`).join(', ')}}`
const constantsSource = `// Code generated by scripts/export-tokens.mjs from the JS modules named below. DO NOT EDIT.

package ditt0

// ${TIMESERIES}

const (
\ttimeseriesRows   = ${ts.ROWS}
\tmultipleRows     = ${ts.MULTIPLE_ROWS}
\tmaxShared        = ${ts.MAX_SHARED}
\tmaxColumns       = ${ts.MAX_COLUMNS}
\trightGap         = ${ts.RIGHT_GAP}
\tup               = ${ts.UP}
\tdown             = ${ts.DOWN}
\tleft             = ${ts.LEFT}
\tright            = ${ts.RIGHT}
\tpoint            = ${ts.POINT}
\tloneGlyph        = ${q(ts.LONE)}
\tniceStepsPerAxis = ${ts.NICE_STEPS_PER_AXIS}
)

var glyphs = map[int]string{${Object.entries(ts.GLYPHS).map(([k, v]) => `${k}: ${q(v)}`).join(', ')}}

var niceMultiples = []float64{${ts.NICE_MULTIPLES.join(', ')}}

// ${STAT}

var bigDigits = map[rune][3]string{${Object.entries(stat.DIGITS).map(([k, v]) => `${JSON.stringify(k).replace(/"/g, "'")}: {${v.map(q).join(', ')}}`).join(', ')}}

const (
\teighths    = ${q(stat.EIGHTHS)}
\tsparkWidth = ${stat.SPARK}
)

// ${LEGEND}

const (
\tmaxName   = ${legend.MAX_NAME}
\tlegendGap = ${legend.ITEM_GAP}
)

// ${UNITS}

// unitStep is one step of a unit's scale: values from divide up are written divided by it, suffix after them
type unitStep struct {
\tdivide float64
\tsuffix string
}

${goSteps('timeSteps', units.TIME)}

${goSteps('bytesSteps', units.BYTES)}

${goSteps('countSteps', units.COUNT)}

${goMap('unitAliases', units.ALIASES)}

var sharedScaleUnits = []string{${units.SHARED_SCALE.map(q).join(', ')}}
`
const constants = execFileSync('gofmt', { input: constantsSource, encoding: 'utf8' })

const check = process.argv.includes('--check')
let stale = false
for (const [path, content] of [[JSON_PATH, json], [GO_PATH, go], [CONSTANTS_PATH, constants]]) {
    let current = null
    try { current = readFileSync(path, 'utf8') } catch {}
    if (current === content) continue
    if (check) { console.error(`${path} is out of date: run node scripts/export-tokens.mjs`); stale = true }
    else writeFileSync(path, content)
}
if (stale) process.exit(1)
