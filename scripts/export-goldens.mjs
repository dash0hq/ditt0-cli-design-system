// Writes the goldens the Go package is tested against: every case in tests/goldens/cases.js drawn by the JS
// components (tests/goldens/render.js), as Claude Code's terminal lays them out, into go/ditt0/testdata/goldens/:
// <name>.txt, its plain text, and <name>.style, each row's runs of colour, bold and dim. cases.json beside them is
// the inputs, which Go's golden test draws and must match byte for byte. tests/goldens/expected.js holds the same
// goldens for `claude plugin test`, which can't read files, so a change to a component that moves its drawing
// fails there until the goldens are written again.
// The components are JSX, which plain Node can't load: bun build (the tool vendor/ is bundled with) bundles them
// first, into a temporary file.
// node scripts/export-goldens.mjs           writes the files
// node scripts/export-goldens.mjs --check   exits 1 if any is out of date
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const DIR = `${root}go/ditt0/testdata/goldens`
const EXPECTED = `${root}tests/goldens/expected.js`

const temp = mkdtempSync(join(tmpdir(), 'ditt0-goldens-'))
let goldens
let cases
try {
    const bundle = join(temp, 'render.mjs')
    // The components' JSX is h/Fragment. The tsconfig that says so is generated by Claude Code and not in git, so
    // name it here for a checkout without it (CI)
    execFileSync('bun', ['build', '--tsconfig-override', 'tests/goldens/jsx.tsconfig.json', 'tests/goldens/render.js', '--target', 'node', '--format', 'esm', '--outfile', bundle], { cwd: root, stdio: ['ignore', 'ignore', 'inherit'] })
    const render = await import(pathToFileURL(bundle).href)
    goldens = render.renderGoldens()
    cases = render.CASES
} finally {
    rmSync(temp, { recursive: true, force: true })
}

const files = new Map([[`${DIR}/cases.json`, `${JSON.stringify(cases, null, 2)}\n`]])
for (const g of goldens) {
    files.set(`${DIR}/${g.name}.txt`, g.text)
    files.set(`${DIR}/${g.name}.style`, g.style)
}
files.set(EXPECTED, [
    '// Generated by scripts/export-goldens.mjs from tests/goldens/cases.js. DO NOT EDIT: run node scripts/export-goldens.mjs',
    '// The goldens as written to go/ditt0/testdata/goldens/, for tests/goldens.test.ts, which can\'t read files',
    `export const EXPECTED = ${JSON.stringify(Object.fromEntries(goldens.map(g => [g.name, { text: g.text, style: g.style }])), null, 2)}`,
    '',
].join('\n'))

const check = process.argv.includes('--check')
let stale = false
// A golden whose case is gone is stale too
const wanted = new Set([...files.keys()].filter(p => p.startsWith(DIR)).map(p => p.slice(DIR.length + 1)))
for (const name of existsSync(DIR) ? readdirSync(DIR) : []) {
    if (wanted.has(name)) continue
    if (check) { console.error(`${DIR}/${name} has no case: run node scripts/export-goldens.mjs`); stale = true }
    else rmSync(`${DIR}/${name}`)
}
mkdirSync(DIR, { recursive: true })
for (const [path, content] of files) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null
    if (current === content) continue
    if (check) { console.error(`${path} is out of date: run node scripts/export-goldens.mjs`); stale = true }
    else writeFileSync(path, content)
}
if (stale) process.exit(1)
console.log(check ? `goldens up to date (${goldens.length})` : `wrote ${goldens.length} goldens to go/ditt0/testdata/goldens`)
