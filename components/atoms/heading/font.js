// Rows of pixels for text in a font (the title font when none is given), a column apart between letters, as many
// rows as the font's glyphs; a character the font lacks draws as its ?, else as a blank its height
export const pixels = (text, font = FONTS.h1) => {
    const height = Object.values(font)[0].length
    const chars = [...String(text)].map(c => font[c] ?? font[c.toUpperCase()] ?? font['?'] ?? Array(height).fill('.'))
    return Array.from({ length: height }, (_, r) => chars.map(g => g[r]).join('.'))
}

// Pixel rows, two to a cell: ▀ the top one, ▄ the bottom one, █ both: eleven rows make six lines, eight four, six three
export const halfBlocks = (rows) => Array.from({ length: Math.ceil(rows.length / 2) }, (_, i) => {
    const top = rows[i * 2]
    const bottom = rows[i * 2 + 1] ?? '.'.repeat(top.length)
    return [...top].map((t, c) => t === '#' ? (bottom[c] === '#' ? '█' : '▀') : bottom[c] === '#' ? '▄' : ' ').join('')
})
