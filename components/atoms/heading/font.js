// Bitmap fonts for titles in a terminal, where text has one size, after Chicago, Susan Kare's system font for the
// first Macintosh: geometric, corners rounded off by a pixel. Three sizes, one a heading level (Heading), each with
// upper and lower case, drawn two pixel rows to a line in half blocks:
// h1: capitals nine pixels tall, stems two wide, descenders two more: eleven rows, six lines
// h2: capitals six pixels tall, stems one wide, x-height four, descenders two: eight rows, four lines
// h3: capitals five pixels tall, x-height three, descenders one: six rows, three lines
// Each glyph is its rows of pixels, # filled, and as wide as its shape, so m and W keep theirs

// A font's glyph makers: cap draws from the top row (capitals, ascenders, digits), low from the x-height, at from any
// row (a t, shorter than an ascender); each pads
// a glyph with blank rows to the font's height
const sized = (height, x) => {
    const at = (top, rows) => {
        const blank = '.'.repeat(rows[0].length)
        return Array.from({ length: height }, (_, r) => rows[r - top] ?? blank)
    }
    return { at, cap: (rows) => at(0, rows), low: (rows) => at(x, rows) }
}
